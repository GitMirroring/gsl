/*
 * Normalize a positive, finite double-double number z as
 *
 *   z = 2^e m,    0.75 <= m.hi < 1.5.
 *
 * Both components of z are scaled by the same exact power of two, so
 * the double-double value of the significand is preserved.  The low
 * component may place m slightly outside the interval; the reduction
 * in the callers tolerates this.
 */
static gsl_dd
log_normalize(const gsl_dd z, int * e)
{
  gsl_dd m;
  double f;

  f = frexp(z.hi, e);           /* 0.5 <= f < 1 */
  if (f < 0.75)
    --(*e);

  m.hi = ldexp(z.hi, -*e);
  m.lo = ldexp(z.lo, -*e);

  return m;
}

/*
 * Select the reduction center c = j/128 nearest to m.hi, where
 * 0.5 <= m.hi <= 1.5, so that |m.hi - c| <= 1/256.  The returned
 * index j lies in [64, 192]; j = 128 corresponds to c = 1, for which
 * log(c) = 0 and no reduction is needed.
 */
static int
log_center_index(const double mhi)
{
  return (int) (128.0 * mhi + 0.5);
}

/*
 * Return log(x) for the special arguments x <= 0, x = +Inf and NaN,
 * following the IEEE conventions of the C library log().
 */
static gsl_dd
log_special(const double x)
{
  gsl_dd r;

  if (x == 0.0)
    r.hi = GSL_NEGINF;
  else if (x > 0.0 || x != x)
    r.hi = x;                   /* +Inf or NaN */
  else
    r.hi = GSL_NAN;

  r.lo = 0.0;

  return r;
}
