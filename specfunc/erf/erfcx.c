#define ONE_OVER_ROOT_PI 5.641895835477562869480794515607725858e-01
#define ERFCX_APPROX 6.71e7
#define ERFCX_NEG_X_MAX 2.662873571375149e+01

static int exp_x2(const double x, gsl_sf_result * result);
static int kernel_cheb(const double x, gsl_sf_result * result);
static int kernel_rational(const double x, gsl_sf_result * result);
static int kernel_maclaurin(const double x, gsl_sf_result * result);
static int erfcx_positive(const double x, gsl_sf_result * result);

/*
 * Compute the scaled complementary error function
 *
 *   erfcx(x) = exp(x^2) erfc(x).
 *
 * For |x| < 0.125 a Maclaurin expansion is used, and for 0.125 <= |x| < 0.5 a piecewise
 * Chebyshev approximation is used.  Positive arguments x >= 0.5 are
 * evaluated using rational approximations, with an asymptotic form for
 * sufficiently large x.  Negative arguments outside the central region
 * are obtained from
 *
 *   erfcx(x) = 2 exp(x^2) - erfcx(-x),
 *
 * using a compensated evaluation of exp(x^2).  GSL_EOVRFLW is
 * returned when the negative-argument result exceeds the double-precision
 * range.
 */

int
gsl_sf_erfcx_e(const double x, gsl_sf_result * result)
{
  int status;
  const double ax = fabs(x);
  gsl_sf_result r, s;

  if (ax < 0.125)
    return kernel_maclaurin(x, result);

  if (ax < 0.5)
    {
      if (x < 0.0)
        {
          status = exp_x2(x, &s);
          if (status)
            return status;

          status = kernel_cheb(-x, &r);
          if (status)
            return status;

          result->val = s.val - r.val + s.val;
          result->err = 2.0 * s.err + r.err + 4.0 * GSL_DBL_EPSILON * (2.0 * fabs(s.val) + fabs(r.val));

          return GSL_SUCCESS;
        }

      return kernel_cheb(x, result);
    }

  if (x < 0.0)
    {
      if (x < -ERFCX_NEG_X_MAX)
        {
          result->val = GSL_POSINF;
          result->err = 0.0;
          return GSL_EOVRFLW;
        }
      else
        {
          status = exp_x2(x, &s);
          if (status)
            return status;

          status = erfcx_positive(-x, &r);
          if (status)
            return status;

          result->val = s.val - r.val + s.val;
          result->err = 2.0 * s.err + r.err + 4.0 * GSL_DBL_EPSILON * (2.0 * fabs(s.val) + fabs(r.val));

          return GSL_SUCCESS;
        }
    }

  return erfcx_positive(x, result);
}

double gsl_sf_erfcx(const double x) { EVAL_RESULT(gsl_sf_erfcx_e(x, &result)); }

