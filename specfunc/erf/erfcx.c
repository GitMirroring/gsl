/*
 * Compute exp(x^2) using a compensated evaluation of x^2.
 *
 * The argument is split into high and low parts so that the rounding error
 * in x^2 can be recovered as a correction r.  The result is then evaluated
 * as
 *
 *   exp(x^2) = exp(h) exp(r) ~= exp(h) (1 + r),
 *
 * where h is the rounded product x*x.  This is used by the negative-x
 * reflection formula for erfcx.
 */

static int
exp_x2(const double x, gsl_sf_result * result)
{
  const double c = 134217729.0 * x;
  const double hx = c - (c - x);
  const double tx = x - hx;
  const double h = x * x;
  const double r = ((hx * hx - h) + 2.0 * hx * tx) + tx * tx;
  const double e = exp(h);

  result->val = e + e * r;
  result->err = 2.0 * GSL_DBL_EPSILON * fabs(result->val) * (1.0 + h);

  return GSL_SUCCESS;
}

/*
 * Evaluate the piecewise Chebyshev approximation to erfcx(x) for
 *
 *   0.125 <= x < 0.5.
 *
 * The interval is divided into 64 subintervals.  frexp() is used to select
 * the appropriate coefficient set and to map x to a local variable
 * t in [-1,1].  The corresponding degree-9 polynomial is then evaluated
 * by Horner's method.
 */

static int
kernel_cheb(const double x, gsl_sf_result * result)
{
  int je;
  const double xm = frexp(x, &je);
  const int ip = (int)(64 * xm);
  const int i = je * 32 + ip + 32;
  const double t = 128 * xm - (1 + 2 * ip);
  const double *C = CHEB_COEFFS[i];

  result->val = (((((((((C[0] * t + C[1]) * t + C[2]) * t + C[3]) * t +
                 C[4]) * t + C[5]) * t + C[6]) * t + C[7]) * t + C[8]) * t + C[9]);
  result->err = 3.0 * GSL_DBL_EPSILON * fabs(result->val);

  return GSL_SUCCESS;
}

/*
 * Compute erfcx(x) for x >= 0.5.
 *
 * Three rational approximations are used on the intervals
 *
 *   0.5 <= x < 1.5,
 *   1.5 <= x < 2.5,
 *   2.5 <= x < 4,
 *
 * followed by a rational approximation in 1/x^2 for x >= 4.
 * For x > ERFCX_APPROX, the leading asymptotic term
 *
 *   erfcx(x) ~= 1 / (sqrt(pi) x)
 *
 * is sufficiently accurate for double precision and is returned directly.
 */

static int
kernel_rational(const double x, gsl_sf_result * result)
{
  static const double p1[6] = { -9.8090592216281240205e-02, 1.78114665841120341155e-01,
                                 1.91003695796775433986e-01, 8.88900368967884466578e-02,
                                 1.95049001251218801359e-02, 1.80424538297014223957e-03 };
  static const double q1[7] = { 1.0, 1.84759070983002217845, 1.42628004845511324508,
                                0.578052804889902404909, 0.12385097467900864233,
                                0.0113385233577001411017, 0.00000337511472483094676155 };
  static const double p2[6] = { -2.43500476207698441272e-02, 3.86540375035707201728e-02,
                                 4.39481896420951629600e-02, 1.75679436311802092299e-02,
                                 3.23962406290842133584e-03, 2.35839115596880717416e-04 };
  static const double q2[6] = { 1.0, 1.53991494948552447182, 0.982403709157920235114,
                                0.325732924782444448493, 0.0563921837420478160373,
                                0.00410369723978904575884 };
  static const double p3[6] = { 2.95276716530971662634e-03, 1.37384425896355332126e-02,
                                8.40807615555585383007e-03, 2.12825620914618649141e-03,
                                2.50269961544794627958e-04, 1.13212406648847561139e-05 };
  static const double q3[6] = { 1.0, 1.04217814166938418171, 0.442597659481563127003,
                                0.0958492726301061423444, 0.0105982906484876531489,
                                0.000479411269521714493907 };
  static const double pc[6] = { 6.58749161529837803157e-04, 1.60837851487422766278e-02,
                                1.25781726111229246204e-01, 3.60344899949804439429e-01,
                                3.05326634961232344035e-01, 1.63153871373020978498e-02 };
  static const double qc[6] = { 2.33520497626869185443e-03, 6.05183413124413191178e-02,
                                5.27905102951428412248e-01, 1.87295284992346047209,
                                2.56852019228982242072, 1.0 };
  static const double y1 = 0.405935764312744140625;
  static const double y2 = 0.50672817230224609375;
  static const double y3 = 0.5405750274658203125;
  const double xm1 = x - 0.5;
  const double xm2 = x - 1.5;
  const double xm3 = x - 3.5;

  if (x > ERFCX_APPROX)
    {
      result->val = ONE_OVER_ROOT_PI / x;
      result->err = 2.0 * GSL_DBL_EPSILON * fabs(result->val);
      return GSL_SUCCESS;
    }

  if (x < 1.5)
    {
      const double P = p1[0] + xm1 * (p1[1] + xm1 * (p1[2] + xm1 * (p1[3] + xm1 * (p1[4] + xm1 * p1[5]))));
      const double Q = q1[0] + xm1 * (q1[1] + xm1 * (q1[2] + xm1 * (q1[3] + xm1 * (q1[4] + xm1 * (q1[5] + xm1 * q1[6])))));
      result->val = (y1 + P / Q) / x;
      result->err = 4.0 * GSL_DBL_EPSILON * fabs(result->val);
      return GSL_SUCCESS;
    }
  else if (x < 2.5)
    {
      const double P = p2[0] + xm2 * (p2[1] + xm2 * (p2[2] + xm2 * (p2[3] + xm2 * (p2[4] + xm2 * p2[5]))));
      const double Q = q2[0] + xm2 * (q2[1] + xm2 * (q2[2] + xm2 * (q2[3] + xm2 * (q2[4] + xm2 * q2[5]))));
      result->val = (y2 + P / Q) / x;
      result->err = 3.0 * GSL_DBL_EPSILON * fabs(result->val);
      return GSL_SUCCESS;
    }
  else if (x < 4.0)
    {
      const double P = p3[0] + xm3 * (p3[1] + xm3 * (p3[2] + xm3 * (p3[3] + xm3 * (p3[4] + xm3 * p3[5]))));
      const double Q = q3[0] + xm3 * (q3[1] + xm3 * (q3[2] + xm3 * (q3[3] + xm3 * (q3[4] + xm3 * q3[5]))));
      result->val = (y3 + P / Q) / x;
      result->err = 3.0 * GSL_DBL_EPSILON * fabs(result->val);
      return GSL_SUCCESS;
    }
  else
    {
      const double ixx = 1.0 / (x * x);
      const double P = pc[0] + ixx * (pc[1] + ixx * (pc[2] + ixx * (pc[3] + ixx * (pc[4] + ixx * pc[5]))));
      const double Q = qc[0] + ixx * (qc[1] + ixx * (qc[2] + ixx * (qc[3] + ixx * (qc[4] + ixx * qc[5]))));
      result->val = (ONE_OVER_ROOT_PI - ixx * P / Q) / x;
      result->err = 3.0 * GSL_DBL_EPSILON * fabs(result->val);
      return GSL_SUCCESS;
    }
}

/*
 * Evaluate the Maclaurin expansion of erfcx(x) for |x| < 0.125.
 *
 * The degree-14 polynomial is evaluated by Horner's method.  This kernel
 * is valid for both positive and negative arguments in the central
 * interval.
 */

static int
kernel_maclaurin(const double x, gsl_sf_result * result)
{
  static const double c[15] = { 1.0000000000000000e+00, -1.1283791670955126e+00,
                                1.0000000000000000e+00, -7.5225277806367508e-01,
                                5.0000000000000000e-01, -3.0090111122547003e-01,
                                1.6666666666666666e-01, -8.5971746064419999e-02,
                                4.1666666666666664e-02, -1.9104832458760001e-02,
                                8.3333333333333332e-03, -3.4736059015927274e-03,
                                1.3888888888888889e-03, -5.3440090793734269e-04,
                                1.9841269841269841e-04 };

  result->val = ((((((((((((((c[14] * x + c[13]) * x + c[12]) * x + c[11]) * x + c[10]) * x +
                              c[9]) * x + c[8]) * x + c[7]) * x + c[6]) * x + c[5]) * x +
                              c[4]) * x + c[3]) * x + c[2]) * x + c[1]) * x + c[0]);
  result->err = 2.0 * GSL_DBL_EPSILON * fabs(result->val);

  return GSL_SUCCESS;
}

/*
 * Evaluation of erfcx(x) for nonnegative x.
 *
 * The Maclaurin kernel is used for x < 0.125, the piecewise Chebyshev
 * kernel for 0.125 <= x < 0.5, and the rational/asymptotic approximations
 * for x >= 0.5.  Very large x is handled directly by the leading
 * asymptotic term.
 */

static int
erfcx_positive(const double x, gsl_sf_result * result)
{
  if (x > ERFCX_APPROX)
    {
      result->val = ONE_OVER_ROOT_PI / x;
      result->err = 2.0 * GSL_DBL_EPSILON * fabs(result->val);
      return GSL_SUCCESS;
    }

  if (x < 0.5)
    {
      if (x < 0.125)
        return kernel_maclaurin(x, result);

      return kernel_cheb(x, result);
    }

  return kernel_rational(x, result);
}
